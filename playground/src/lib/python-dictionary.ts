// These are individual function choices, not complete program candidates.
export const PYTHON_FUNCTIONS = Object.freeze({
  print: "Display the chosen string, followed by a newline.",
  len: "Return the number of characters in the chosen string; this does not display it.",
  repr: "Return a quoted representation of the chosen string; this does not display it.",
});
export type PythonFunction = keyof typeof PYTHON_FUNCTIONS;

export function buildPythonStatement(selectedFunction: PythonFunction, value: string): string {
  if (typeof selectedFunction !== "string" || !Object.hasOwn(PYTHON_FUNCTIONS, selectedFunction)) {
    throw new Error("Choose an allowed Python function: print, len, or repr.");
  }
  if (typeof value !== "string" || Array.from(value).length > 1000 || value.includes("\0")) {
    throw new Error("Python string values must contain at most 1000 Unicode characters, without NUL.");
  }
  // JSON string escapes are also valid in a Python double-quoted string literal.
  // Escaping the whole value keeps quotes, backslashes and newlines inside it.
  const literal = JSON.stringify(value);
  return `${selectedFunction}(${literal})\n`;
}

// Completion recognizes only a statement generated by this supported builder.
// User-supplied Python is never evaluated by the completion check.
export function isPythonPrintProgram(content: string, output: string): boolean {
  try { return content === buildPythonStatement("print", output); }
  catch { return false; }
}
